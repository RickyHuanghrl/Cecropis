"""Build the CLI grammar without opening a workspace or starting tasks."""
import argparse
from pathlib import Path
from ..service_control import version


def build_parser():
    parser=argparse.ArgumentParser(prog='cecropis',description='Cecropis: local connectome exploration and intervention analysis')
    parser.add_argument('--version', action='version', version='Cecropis '+version())
    parser.add_argument('--workspace',type=Path,help='Workspace JSON; its relative paths use the configuration directory')
    parser.add_argument('--case',type=Path)
    parser.add_argument('--index',type=Path)
    parser.add_argument('--cases',type=Path)
    parser.add_argument('--runs',type=Path)
    parser.add_argument('--raw',type=Path)
    subs=parser.add_subparsers(dest='command',required=True)
    local=subs.add_parser('local-submit')
    local.add_argument('--type',choices=['response_exploration','operation_search'],required=True)
    local.add_argument('--config',type=Path,required=True)
    subs.add_parser('local-list')
    for name in ('local-read','local-result','local-check','local-pause','local-cancel','local-copy'):
        sub=subs.add_parser(name)
        sub.add_argument('--id',required=True)
    local=subs.add_parser('local-run')
    local.add_argument('--ids',nargs='+',required=True)

    batch=subs.add_parser('responses')
    batch.add_argument('--config',type=Path,required=True)
    batch.add_argument('--preview',action='store_true')
    batch_read=subs.add_parser('responses-read')
    batch_read.add_argument('--report',type=Path,required=True)
    batch_nodes=subs.add_parser('responses-nodes')
    batch_nodes.add_argument('--report',type=Path,required=True)
    batch_nodes.add_argument('--condition',type=int,required=True)
    batch_nodes.add_argument('--group',type=int)
    batch_nodes.add_argument('--other',type=int)
    batch_nodes.add_argument('--exclude-inputs',action='store_true')
    batch_nodes.add_argument('--mode',choices=['baseline','intervention','delta'],default='baseline')
    batch_nodes.add_argument('--offset',type=int,default=0)
    batch_nodes.add_argument('--limit',type=int,default=50)
    for name in ('responses-curves','responses-export'):
        sub=subs.add_parser(name)
        sub.add_argument('--report',type=Path,required=True)
        sub.add_argument('--condition',type=int,required=True)
        sub.add_argument('--group',type=int)
        sub.add_argument('--observation-name',help='Name of the additional response group observation')
        if name=='responses-export':
            sub.add_argument('--output',type=Path,required=True)
            sub.add_argument('--name',required=True)
    subs.add_parser('spatial-overview')
    space_nodes=subs.add_parser('spatial-locate')
    space_nodes.add_argument('--ids',nargs='+',required=True)
    space_geo=subs.add_parser('spatial-geometry')
    space_geo.add_argument('--ids',nargs='+',required=True)
    for name in ('skeleton-status','skeleton-update','skeleton-node','skeleton-query'):
        skeleton=subs.add_parser(name)
        skeleton.add_argument('--directory',type=Path,help='Read-only precomputed skeleton directory; relative to cwd')
        skeleton.add_argument('--cache',type=Path,help='Independent derived cache; relative to cwd')
        if name=='skeleton-status':
            skeleton.add_argument('--offset',type=int,default=0)
            skeleton.add_argument('--limit',type=int,default=20)
        elif name=='skeleton-update':
            skeleton.add_argument('--max-files',type=int)
            skeleton.add_argument('--max-input-mib',type=float,default=512)
            skeleton.add_argument('--max-cache-mib',type=float,default=2048)
            skeleton.add_argument('--progress',action='store_true',help='Write committed geometry progress to stderr')
        elif name=='skeleton-query':
            skeleton.add_argument('--bounds',type=float,nargs=6,required=True,metavar='XYZ')
            skeleton.add_argument('--limit',type=int,default=512)
        else:
            skeleton.add_argument('--id',required=True)
            skeleton.add_argument('--level',type=int,default=0)
            skeleton.add_argument('--output',type=Path,help='Explicitly export one published LOD binary; never prepares geometry')
    ops=subs.add_parser('operation-search')
    ops.add_argument('--config',type=Path,required=True)
    ops.add_argument('--preview',action='store_true')
    ops_read=subs.add_parser('operation-search-read')
    ops_read.add_argument('--report',type=Path,required=True)
    ops_eval=subs.add_parser('operation-search-evaluate')
    ops_eval.add_argument('--report',type=Path,required=True)
    ops_eval.add_argument('--ids',nargs='*',required=True)
    ops_eval.add_argument('--extra',type=Path)
    grouping=subs.add_parser('group-analyze')
    grouping.add_argument('--config',type=Path,required=True)
    grouping.add_argument('--preview',action='store_true')
    grouping.add_argument('--reuse-case',type=Path,help='Matching saved scope used only as a structural CSR cache')
    group_read=subs.add_parser('group-read')
    group_read.add_argument('--report',type=Path,required=True)
    for name in ('group-features','group-similar'):
        group=subs.add_parser(name)
        group.add_argument('--report',type=Path,required=True)
        group.add_argument('--direction',choices=['incoming','outgoing'],default='outgoing')
        if name=='group-features':
            group.add_argument('--a',type=int,required=True)
            group.add_argument('--b',type=int,required=True)
        else:
            group.add_argument('--group',type=int,required=True)
            group.add_argument('--limit',type=int,default=20)
    group_members=subs.add_parser('group-members')
    group_members.add_argument('--report',type=Path,required=True)
    group_members.add_argument('--groups',nargs='+',type=int,required=True)
    group_members.add_argument('--filters',type=Path)
    group_pair=subs.add_parser('group-pair')
    group_pair.add_argument('--report',type=Path,required=True)
    group_pair.add_argument('--source',type=int,required=True)
    group_pair.add_argument('--target',type=int,required=True)
    group_pair.add_argument('--limit',type=int,default=50)
    group_pair.add_argument('--offset',type=int,default=0)
    group_pair.add_argument('--scan-limit',type=int,default=1000000)
    find=subs.add_parser('find')
    find.add_argument('--query')
    find.add_argument('--type')
    find.add_argument('--body-id')
    find.add_argument('--category',choices=['neuron','glia','other','unannotated','all'],default='neuron')
    find.add_argument('--filters',type=Path)
    find.add_argument('--limit',type=int,default=100)
    find.add_argument('--offset',type=int,default=0)
    neighbors=subs.add_parser('neighbors')
    neighbors.add_argument('--id',required=True)
    neighbors.add_argument('--direction',choices=['incoming','outgoing'],default='incoming')
    neighbors.add_argument('--limit',type=int,default=100)
    case=subs.add_parser('case')
    case.add_argument('--selection',type=Path,required=True)
    case.add_argument('--destination',type=Path)
    scope=subs.add_parser('scope')
    scope.add_argument('--config',type=Path,required=True)
    boundary=subs.add_parser('scope-boundary')
    boundary.add_argument('--config',type=Path)
    boundary.add_argument('--ids',nargs='*')
    external=subs.add_parser('scope-external')
    external.add_argument('--ids',nargs='+',required=True)
    external.add_argument('--category',default='neuron')
    external.add_argument('--scan-limit',type=int,default=1000000)
    external.add_argument('--limit',type=int,default=50)
    external.add_argument('--offset',type=int,default=0)
    expansion=subs.add_parser('scope-expand')
    expansion.add_argument('--config',type=Path,required=True)
    expansion.add_argument('--preview',action='store_true')
    expansion_read=subs.add_parser('scope-expansion-read')
    expansion_read.add_argument('--report',type=Path,required=True)
    fixed_scopes=subs.add_parser('compare-scope-plans')
    fixed_scopes.add_argument('--config',type=Path,required=True)
    fixed_scopes.add_argument('--preview',action='store_true')
    fixed_read=subs.add_parser('scope-plan-read')
    fixed_read.add_argument('--report',type=Path,required=True)
    fixed_read.add_argument('--task-id')
    for name in ('task-read','task-preview','task-prepare','task-run'):
        sub=subs.add_parser(name)
        sub.add_argument('--definition',type=Path,required=True)
        if name in ('task-preview','task-prepare'):
            sub.add_argument('--budgets',type=Path)
        if name=='task-run':
            sub.add_argument('--scope',type=Path,help='An existing exact scope; never creates a scope')
    task_export=subs.add_parser('task-export')
    task_export.add_argument('--source',type=Path,required=True)
    task_export.add_argument('--request',type=Path,help='JSON selecting actual conditions or fixed plans')
    task_export.add_argument('--name',required=True)
    task_export.add_argument('--description',default='')
    task_export.add_argument('--output',type=Path,required=True)
    for name in ('report-preview','report-export'):
        report=subs.add_parser(name)
        report.add_argument('--source',type=Path,required=True,help='Saved comparison directory or comparison.json; never reads activity archives')
        report.add_argument('--condition',dest='condition_names',action='append',help='Exact saved condition name; repeat to select multiple')
        report.add_argument('--language',choices=('zh-CN','en','ja','fr','de','es'),default='en',help='Report display language; does not change results')
        report.add_argument('--max-bytes',type=int,default=16*1024*1024)
        if name=='report-export':
            report.add_argument('--destination',type=Path,required=True,help='New output directory; existing directories are never overwritten')
    pathways=subs.add_parser('pathways')
    pathways.add_argument('--config',type=Path)
    pathways.add_argument('--global',dest='global_graph',action='store_true')
    for name in ('run','forward'):
        run=subs.add_parser(name)
        run.add_argument('--config',type=Path)
        run.add_argument('--record-mode',choices=['selected','all','none'])
        run.add_argument('--record-ids',nargs='+')
        run.add_argument('--record-stride',type=int)
        run.add_argument('--record-steps',nargs='+',type=int)
    comp=subs.add_parser('compare')
    comp.add_argument('--config',type=Path,required=True)
    operations=subs.add_parser('operations-compare')
    operations.add_argument('--config',type=Path,required=True)
    operation_preview=subs.add_parser('intervention-preview')
    operation_preview.add_argument('--config',type=Path,required=True)
    operation_edges=subs.add_parser('intervention-edges')
    operation_edges.add_argument('--source',nargs='+',required=True)
    operation_edges.add_argument('--target',nargs='+',required=True)
    operation_edges.add_argument('--max-edges',type=int,default=100000)
    operation_edges.add_argument('--max-bytes',type=int,default=64*1024**2)
    comparison_read=subs.add_parser('comparison-read')
    comparison_read.add_argument('--source',type=Path,required=True)
    scopes=subs.add_parser('compare-scopes')
    scopes.add_argument('--config',type=Path,required=True)
    scopes.add_argument('--preview',action='store_true')
    joint=subs.add_parser('joint-search')
    joint.add_argument('--config',type=Path,required=True)
    joint.add_argument('--preview',action='store_true')
    joint.add_argument('--context',action='store_true',help='Compute baselines, candidate ranking and threshold scales without perturbations')
    joint.add_argument('--candidate-order',choices=['signal_path','body_id'])
    evaluation=subs.add_parser('joint-evaluate')
    evaluation.add_argument('--report',type=Path,required=True)
    evaluation.add_argument('--extra-conditions',type=Path)
    evaluation.add_argument('--ids',nargs='+',help='Exact IDs of a saved evaluated plan; defaults to best')
    timing=subs.add_parser('timing-explore')
    timing.add_argument('--config',type=Path,required=True)
    timing.add_argument('--preview',action='store_true')
    timing_plan=subs.add_parser('timing-evaluate')
    timing_plan.add_argument('--report',type=Path,required=True)
    timing_plan.add_argument('--start',type=int,required=True)
    timing_plan.add_argument('--duration',type=int,required=True)
    for name in ('search','sensitivity'):
        sub=subs.add_parser(name)
        sub.add_argument('--config',type=Path)
        sub.add_argument('--budget',type=int)
        sub.add_argument('--target-output')
        sub.add_argument('--target-metric',choices=['relative','absolute'])
        sub.add_argument('--protected-limits',type=Path,help='JSON map: observation -> {metric, max_loss}')
        sub.add_argument('--candidate-policy',choices=['internal_only','allow_endpoints'])
        sub.add_argument('--candidate-order',choices=['signal_path','body_id'])
        sub.add_argument('--context',action='store_true',help='Inspect baselines and candidate ranking without perturbation search')
        if name=='search':
            sub.add_argument('--max-nodes',type=int)
            sub.add_argument('--max-protected-loss',type=float)
            sub.add_argument('--min-target-loss',type=float)
            sub.add_argument('--shortlist',type=int)
            sub.add_argument('--swap-passes',type=int)
    serv = subs.add_parser('serve', aliases=['start'], help='Start the local workbench in this terminal')
    serv.add_argument('--port', type=int, default=8501)
    serv.add_argument('--geometry', type=Path)
    serv.add_argument('--no-banner', action='store_true', help='Hide the interactive ASCII wordmark')
    serv.add_argument('--access-log', action='store_true', help='Log all HTTP requests, including successful access traffic')
    for name in ('status', 'stop'):
        control = subs.add_parser(name, help='Inspect or gracefully stop one local Cecropis service')
        control.add_argument('--port', type=int, default=8501)
    serv.add_argument('--skeleton-directory',type=Path,help='Read-only precomputed geometry directory; relative to cwd')
    serv.add_argument('--skeleton-cache',type=Path,help='Derived precomputed cache directory; relative to cwd')
    geo=subs.add_parser('geometry')
    geo.add_argument('--directory',type=Path)
    geo.add_argument('--id')
    rp=subs.add_parser('replay-prepare')
    rp_source=rp.add_mutually_exclusive_group(required=True)
    rp_source.add_argument('--source',type=Path)
    rp_source.add_argument('--config',type=Path)
    rp.add_argument('--request',type=Path)
    rp.add_argument('--preview',action='store_true')
    rr=subs.add_parser('replay-read')
    rr.add_argument('--replay',type=Path,required=True)
    rr.add_argument('--start',type=int)
    rr.add_argument('--stop',type=int)
    rr.add_argument('--limit',type=int,default=100)
    rr.add_argument('--step',type=int)
    rr.add_argument('--node')
    rr.add_argument('--edge')
    dp=subs.add_parser('difference-prepare')
    dp_source=dp.add_mutually_exclusive_group(required=True)
    dp_source.add_argument('--source',type=Path)
    dp_source.add_argument('--config',type=Path)
    dp.add_argument('--request',type=Path)
    dp.add_argument('--preview',action='store_true')
    dr=subs.add_parser('difference-read')
    dr.add_argument('--differences',type=Path,required=True)
    dr.add_argument('--sort',choices=['absolute','decrease','increase'])
    dr.add_argument('--body-id')
    dr.add_argument('--type-filter')
    dr.add_argument('--include-endpoints',action='store_true')
    dr.add_argument('--offset',type=int)
    dr.add_argument('--limit',type=int,default=50)
    dr.add_argument('--node')
    dr.add_argument('--neighbors',choices=['both','upstream','downstream'])
    scene=subs.add_parser('session-read')
    scene.add_argument('--session',type=Path,required=True)
    reduction=subs.add_parser('reduction-analyze')
    reduction.add_argument('--config',type=Path,required=True)
    reduction.add_argument('--preview',action='store_true')
    reduction_read=subs.add_parser('reduction-read')
    reduction_read.add_argument('--report',type=Path,required=True)
    reduction_curves=subs.add_parser('reduction-evaluate')
    reduction_curves.add_argument('--report',type=Path,required=True)
    reduction_curves.add_argument('--ids',nargs='*',help='Exact completed set; empty --ids means no intervention')
    reduction_curves.add_argument('--include-original',action='store_true')
    return parser
